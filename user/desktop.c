static int
utf8_next_cp(const char **pp, uint *cp)
{
  const uchar *p = (const uchar *)*pp;
  uchar c;

  if(*p == 0)
    return 0;
  c = *p;
  if(c < 0x80u){
    *cp = c;
    (*pp)++;
    return 1;
  }
  if((c & 0xf0u) == 0xe0u && p[1] != 0 && p[2] != 0){
    *cp = ((uint)(c & 0x0fu) << 12) | ((uint)(p[1] & 0x3fu) << 6) |
          (uint)(p[2] & 0x3fu);
    *pp += 3;
    return 1;
  }
  *cp = '?';
  (*pp)++;
  return 1;
}

static void
draw_utf8_in_box(int x0, int y0, int xmax, const char *text, pix_t fg, pix_t bg)
{
  int cx = x0;
  int cy = y0;
  const char *p = text;
  uint cp;

  while(utf8_next_cp(&p, &cp)){
    const uchar *g;

    if(cp == 0)
      break;
    if(cp < 0x80u){
      if(cx + FONT_CELL_W > xmax){
        cx = x0;
        cy += FONT_CELL_H + ABOUT_LINE_GAP;
      }
      draw_char(cx, cy, (char)cp, fg, bg);
      cx += FONT_CELL_W;
    } else {
      g = glyph_for_cp(cp);
      if(!g)
        continue;
      if(cx + 16 > xmax){
        cx = x0;
        cy += FONT_CELL_H + ABOUT_LINE_GAP;
      }
      draw_glyph16_bold(cx, cy, g, fg, bg);
      cx += 16;
    }
  }
}

