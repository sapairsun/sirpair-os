static int
calc_hit_btn(int x, int y)
{
  int gx = CALC_GRID_X;
  int gy = CALC_GRID_Y;
  int col, row;
  int lx, ly;

  if(x < gx || y < gy)
    return -1;
  col = (x - gx) / (CALC_BTN_W + CALC_BTN_GAP);
  row = (y - gy) / (CALC_BTN_H + CALC_BTN_GAP);
  if(col < 0 || col > 3 || row < 0 || row > 3)
    return -1;
  lx = (x - gx) % (CALC_BTN_W + CALC_BTN_GAP);
  ly = (y - gy) % (CALC_BTN_H + CALC_BTN_GAP);
  if(lx >= CALC_BTN_W || ly >= CALC_BTN_H)
    return -1;
  return row * 4 + col;
}

