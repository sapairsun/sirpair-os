static void
fill_rect(int x0, int y0, int ww, int hh, pix_t c)
{
  int x, y;
  for(y = y0; y < y0 + hh; y++){
    if(y < 0 || y >= H)
      continue;
    for(x = x0; x < x0 + ww; x++){
      int o;
      if(x < 0 || x >= W)
        continue;
      o = (y * W + x) * 3;
      frame[o] = c.b;
      frame[o + 1] = c.g;
      frame[o + 2] = c.r;
    }
  }
}

static void
draw_char(int x0, int y0, char ch, pix_t fg, pix_t bg)
{
  int row, col;
  uchar bits;
  uchar c;

  c = (uchar)ch;
  if(c > 127)
    c = ' ';
  for(row = 0; row < FONT_CELL_H; row++){
    bits = g_font8x16[c][row];
    for(col = 0; col < FONT_CELL_W; col++){
      int x = x0 + col;
      int y = y0 + row;
      int o;
      pix_t t;
      if(x < 0 || x >= W || y < 0 || y >= H)
        continue;
      t = (bits & (0x80 >> col)) ? fg : bg;
      o = (y * W + x) * 3;
      frame[o] = t.b;
      frame[o + 1] = t.g;
      frame[o + 2] = t.r;
    }
  }
}

static void
draw_str(int x0, int y0, const char *s, pix_t fg, pix_t bg)
{
  int x = x0;
  while(*s){
    draw_char(x, y0, *s++, fg, bg);
    x += FONT_CELL_W;
  }
}

/* Unifont 16×16：每行 2 字节，高位字节最左像素为 bit7 */
static int
glyph16_bit(const uchar *g, int col, int row)
{
  uchar hi, lo;

  if(col < 0 || col > 15 || row < 0 || row > 15)
    return 0;
  hi = g[row * 2];
  lo = g[row * 2 + 1];
  if(col < 8)
    return (hi >> (7 - col)) & 1;
  return (lo >> (15 - col)) & 1;
}

/* 加粗：与左、上、左上邻域做或，模拟粗体笔画 */
static void
draw_glyph16_bold(int x0, int y0, const uchar *g, pix_t fg, pix_t bg)
{
  int row, col;

  for(row = 0; row < 16; row++){
    for(col = 0; col < 16; col++){
      int on;
      int x = x0 + col;
      int y = y0 + row;
      int o;
      pix_t t;

      on = glyph16_bit(g, col, row);
      on |= glyph16_bit(g, col - 1, row);
      on |= glyph16_bit(g, col, row - 1);
      on |= glyph16_bit(g, col - 1, row - 1);
      if(x < 0 || x >= W || y < 0 || y >= H)
        continue;
      t = on ? fg : bg;
      o = (y * W + x) * 3;
      frame[o] = t.b;
      frame[o + 1] = t.g;
      frame[o + 2] = t.r;
    }
  }
}

