static void
handle_click(int x, int y)
{
  int px = PANEL_X, py = PANEL_Y, pw = PANEL_W;
  int bid;

  if(y >= TASKBAR_Y && y < H){
    if(inside(x, y, AB_X, AB_Y, AB_W, AB_H)){
      about_open = 1;
      win_top = WIN_ABOUT;
      return;
    }
    if(inside(x, y, SB_X, SB_Y, SB_W, SB_H))
      shutdown();
    return;
  }

  if(about_open){
    if(inside(x, y, ABOUT_X + ABOUT_W - CLOSE_SZ - 4, ABOUT_Y + 2, CLOSE_SZ,
              CLOSE_SZ)){
      about_open = 0;
      return;
    }
    if(inside(x, y, ABOUT_X, ABOUT_Y, ABOUT_W, ABOUT_H))
      return;
    about_open = 0;
  }

  if(calc_open){
    if(inside(x, y, CALC_X + CALC_W - CLOSE_SZ - 4, CALC_Y + 2, CLOSE_SZ, CLOSE_SZ)){
      calc_open = 0;
      return;
    }
    bid = calc_hit_btn(x, y);
    if(bid >= 0){
      calc_press_btn(bid);
      return;
    }
    if(inside(x, y, CALC_X, CALC_Y, CALC_W, CALC_H))
      return;
    if(inside(x, y, ICON2_X, ICON2_Y, ICON_W, ICON_H)){
      calc_clear();
      return;
    }
    if(inside(x, y, ICON_X, ICON_Y, ICON_W, ICON_H)){
      load_dir();
      panel_open = 1;
      win_top = WIN_PANEL;
      return;
    }
    calc_open = 0;
    return;
  }

  if(panel_open){
    if(inside(x, y, px + pw - CLOSE_SZ - 4, py + 2, CLOSE_SZ, CLOSE_SZ)){
      panel_open = 0;
      return;
    }
    if(inside(x, y, px, py, pw, PANEL_H))
      return;
    panel_open = 0;
    return;
  }

  if(inside(x, y, ICON2_X, ICON2_Y, ICON_W, ICON_H)){
    calc_open = 1;
    calc_clear();
    win_top = WIN_CALC;
    return;
  }

  if(inside(x, y, ICON_X, ICON_Y, ICON_W, ICON_H)){
    load_dir();
    panel_open = 1;
    win_top = WIN_PANEL;
  }
}

int
main(void)
{
  struct mouse_event me;
  uchar c;

  printf(1, DM_START);
  mouseinit();
  guimode(1);
  mx = W / 2;
  my = H / 2;
  prev_btn = 0;
  panel_open = 0;
  calc_open = 0;
  about_open = 0;
  win_top = WIN_NONE;
  calc_clear();
  set_input_raw(1);

  for(;;){
    paint();

    while(mousepoll(&me) > 0){
      mx += me.dx;
      my += me.dy;
      if(mx < 0)
        mx = 0;
      if(my < 0)
        my = 0;
      if(mx >= W)
        mx = W - 1;
      if(my >= H)
        my = H - 1;

      if((me.buttons & 1) && !(prev_btn & 1))
        handle_click(mx, my);
      prev_btn = me.buttons;
    }

    if(fdready(0, 0)){
      if(read(0, &c, 1) == 1 && c == 'q')
        break;
    }
    sleep(1);
  }

  guimode(0);
  set_input_raw(0);
  printf(1, DM_END);
  exit(0);
}
