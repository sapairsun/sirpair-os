static void
trim_dirent_name(char *out, const char *in)
{
  int i;
  for(i = 0; i < DIRSIZ && in[i]; i++)
    out[i] = in[i];
  out[i] = 0;
}

static void
load_dir(void)
{
  int fd;
  struct dirent de;
  struct stat st;

  nent = 0;
  fd = open(".", O_RDONLY);
  if(fd < 0)
    return;
  while(read(fd, &de, sizeof(de)) == sizeof(de)){
    if(de.inum == 0)
      continue;
    if(nent >= MAXENT)
      break;
    trim_dirent_name(ents[nent].name, de.name);
    if(ents[nent].name[0] == 0){
      memmove(ents[nent].name, de.name, DIRSIZ);
      ents[nent].name[DIRSIZ] = 0;
    }
    if(stat(ents[nent].name, &st) < 0){
      ents[nent].type = 0;
    } else {
      ents[nent].type = st.type;
    }
    nent++;
  }
  close(fd);
}

static void
int2str(int n, char *buf, int nbuf)
{
  char tmp[12];
  int i = 0, j = 0, neg = 0;

  if(nbuf < 2){
    if(nbuf == 1)
      buf[0] = 0;
    return;
  }
  if(n < 0){
    neg = 1;
    if(n == -2147483647 - 1){
      strcpy(buf, "-2147483648");
      return;
    }
    n = -n;
  }
  if(n == 0){
    buf[0] = '0';
    buf[1] = 0;
    return;
  }
  while(n > 0 && i < 11){
    tmp[i++] = '0' + (n % 10);
    n /= 10;
  }
  j = 0;
  if(neg)
    buf[j++] = '-';
  while(i > 0 && j < nbuf - 1)
    buf[j++] = tmp[--i];
  buf[j] = 0;
}

static void
calc_refresh_disp(void)
{
  int show;

  if(calc_err){
    strcpy(calc_disp, "Err");
    return;
  }
  /*
   * 已按下运算符、正等待下一段数字时，内部 calc_ent 会置 0，
   * 此时应继续显示累加侧 calc_acc，避免界面跳成 0（像被清空）。
   */
  if(calc_op != 0 && calc_ent == 0 && !calc_after_eq)
    show = calc_acc;
  else
    show = calc_ent;
  int2str(show, calc_disp, sizeof(calc_disp));
}

static void
calc_clear(void)
{
  calc_acc = 0;
  calc_ent = 0;
  calc_op = 0;
  calc_err = 0;
  calc_after_eq = 0;
  calc_refresh_disp();
}

static int
calc_do(int a, int b, int op)
{
  if(op == '+')
    return a + b;
  if(op == '-')
    return a - b;
  if(op == '*')
    return a * b;
  if(op == '/'){
    if(b == 0){
      calc_err = 1;
      return 0;
    }
    return a / b;
  }
  return b;
}

static void
calc_on_op(int newop)
{
  if(calc_err){
    calc_clear();
    return;
  }
  calc_after_eq = 0;
  if(calc_op != 0){
    calc_acc = calc_do(calc_acc, calc_ent, calc_op);
    if(calc_err){
      calc_refresh_disp();
      return;
    }
  } else
    calc_acc = calc_ent;
  calc_ent = 0;
  calc_op = newop;
  calc_refresh_disp();
}

static void
calc_on_eq(void)
{
  if(calc_err){
    calc_clear();
    return;
  }
  if(calc_op == 0)
    return;
  calc_acc = calc_do(calc_acc, calc_ent, calc_op);
  if(calc_err){
    calc_refresh_disp();
    return;
  }
  calc_ent = calc_acc;
  calc_op = 0;
  calc_after_eq = 1;
  calc_refresh_disp();
}

static void
calc_on_digit(int d)
{
  if(calc_err){
    calc_clear();
    calc_ent = d;
    calc_refresh_disp();
    return;
  }
  if(calc_after_eq){
    calc_ent = d;
    calc_after_eq = 0;
    calc_refresh_disp();
    return;
  }
  if(calc_ent > 100000000)
    return;
  calc_ent = calc_ent * 10 + d;
  calc_refresh_disp();
}

static void
calc_press_btn(int bid)
{
  static const char map[] = "789/456*123-0=+C";
  char k;

  if(bid < 0 || bid > 15)
    return;
  k = map[bid];
  if(k >= '0' && k <= '9'){
    calc_on_digit(k - '0');
    return;
  }
  if(k == 'C'){
    calc_clear();
    return;
  }
  if(k == '='){
    calc_on_eq();
    return;
  }
  calc_on_op(k);
}

